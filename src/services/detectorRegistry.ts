export function getStoredDetectorModels(): ModelOption[] {
  if (typeof window !== 'undefined') {
    try {
      const savedReadyIds: string[] = JSON.parse(
        localStorage.getItem('vision_downloaded_models') || '["tfjs-coco-ssd"]'
      );
      return INITIAL_DETECTOR_MODELS.map((m) =>
        savedReadyIds.includes(m.id)
          ? { ...m, downloadStatus: 'ready' as const, downloadProgress: 100 }
          : m
      );
    } catch {
      return INITIAL_DETECTOR_MODELS;
    }
  }
  return INITIAL_DETECTOR_MODELS;
}

